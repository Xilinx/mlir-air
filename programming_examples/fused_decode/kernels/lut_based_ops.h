// 4x-finer SiLU LUT: 256 segments of 2^-4 over the SAME [-8, 8) range the
// 64-segment table below covers, so nothing that used to be in range falls out
// of it. Same chord fit (each segment interpolates its own endpoints) and same
// storage order (blocks of 4 segments, each block stored twice).
//
// Why: `aie::linear_approx` error goes as step^2, and the shipped 0.25 step is
// sized for a range LFM2 never uses -- its SwiGLU gate is p99 = 1.2, max 4.1
