"""Generate portable client entries and the package manifest from canonical files."""

import argparse
import hashlib
import json
from pathlib import Path
import re

PACKAGE = Path(__file__).resolve().parents[1]
ROOT = PACKAGE.parent


def generated(package=PACKAGE):
    root = package.parent
    files = {}
    for skill in sorted(package.glob("skills/*/SKILL.md")):
        front = re.match(r"---\n.*?\n---\n", skill.read_text(encoding="utf-8"), re.S)
        if not front:
            raise ValueError(f"missing skill frontmatter: {skill}")
        for client in (".agents", ".claude"):
            header = front.group()
            if client == ".claude" and skill.parent.name == "deploy-new-llm":
                header = (
                    header[:-4]
                    + 'argument-hint: "<hugging-face-id> [deployment requirements]"\n---\n'
                )
            files[root / client / "skills" / skill.parent.name / "SKILL.md"] = (
                header
                + "\n<!-- Generated by agentic/tools/sync_package.py. -->\n\n"
                + f"Read and follow the [canonical {skill.parent.name} skill](../../../agentic/skills/{skill.parent.name}/SKILL.md).\n"
                + "Resolve its relative references from that canonical directory.\n"
            )
    payload = []
    # Path ordering folds case on Windows; use portable strings for the manifest.
    for path in sorted(
        package.rglob("*"), key=lambda path: path.relative_to(package).as_posix()
    ):
        if (
            path.is_file()
            and path.name != "MANIFEST.json"
            and "__pycache__" not in path.parts
            and not path.name.endswith(".pyc")
        ):
            data = path.read_bytes()
            payload.append(
                dict(
                    path=path.relative_to(package).as_posix(),
                    bytes=len(data),
                    sha256=hashlib.sha256(data).hexdigest(),
                )
            )
    manifest = dict(
        schema_version=1,
        version="0.1.0",
        skills=[p.parent.name for p in sorted(package.glob("skills/*/SKILL.md"))],
        provenance="Extends the MLArchSys'26 work, co-located with ISCA 2026: https://arxiv.org/abs/2606.07586",
        files=payload,
    )
    files[package / "MANIFEST.json"] = json.dumps(manifest, indent=2) + "\n"
    return files


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    differences = []
    for path, text in generated().items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            differences.append(str(path.relative_to(ROOT)))
            if not a.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    expected = {p.parent.name for p in PACKAGE.glob("skills/*/SKILL.md")}
    for client in (".agents", ".claude"):
        actual = {p.parent.name for p in (ROOT / client / "skills").glob("*/SKILL.md")}
        obsolete = {name for name in actual - expected if name.startswith("phase-")}
        if obsolete:
            raise ValueError(f"obsolete registrations in {client}: {sorted(obsolete)}")
    print(
        json.dumps(
            dict(mode="check" if a.check else "write", differing_files=differences),
            indent=2,
        )
    )
    return int(a.check and bool(differences))


if __name__ == "__main__":
    raise SystemExit(main())
